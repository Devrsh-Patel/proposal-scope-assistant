// ─── Export Logic ─────────────────────────────────────────────────────────
// Exports the reviewed proposal draft to DOCX and PDF.
// Never silently removes unresolved markers or uncertainty labels.

import {
  Document,
  Packer,
  Paragraph,
  TextRun,
  HeadingLevel,
  AlignmentType,
  BorderStyle,
} from 'docx';
import jsPDF from 'jspdf';
import type { ProposalDraft, ExportOptions, ProposalSection, ServicePackage } from '../types';

// ─── Text / Markdown Stripping ───────────────────────────────────────────────

function stripMarkdown(text: string): string {
  return text
    .replace(/\*\*(.*?)\*\*/g, '$1') // bold
    .replace(/\*(.*?)\*/g, '$1')     // italic
    .replace(/`(.*?)`/g, '$1')       // inline code
    .replace(/^#+\s+/gm, '')         // headings
    .replace(/^>\s+/gm, '> ')        // blockquotes
    .replace(/^[-*+]\s+/gm, '• ')    // bullets
    .trim();
}

// ─── DOCX Export ─────────────────────────────────────────────────────────────

function sectionToDocxParagraphs(section: ProposalSection, options: ExportOptions): Paragraph[] {
  const paras: Paragraph[] = [];

  // Section heading
  paras.push(
    new Paragraph({
      text: section.title,
      heading: HeadingLevel.HEADING_2,
      spacing: { before: 300, after: 100 },
    })
  );

  // Status badge
  if (section.status !== 'confirmed') {
    const badge =
      section.status === 'missing'
        ? '[MISSING — INFORMATION NOT PROVIDED]'
        : section.status === 'suggested'
        ? '[SUGGESTED WORDING — REVIEW REQUIRED]'
        : '[UNRESOLVED — ACTION REQUIRED]';

    paras.push(
      new Paragraph({
        children: [
          new TextRun({ text: badge, bold: true, color: section.status === 'missing' ? 'C0392B' : '8E6A00', italics: true }),
        ],
        spacing: { after: 80 },
      })
    );
  }

  // Content paragraphs
  const lines = section.content.split('\n');
  for (const line of lines) {
    const stripped = stripMarkdown(line);
    if (!stripped) {
      paras.push(new Paragraph({ text: '', spacing: { after: 60 } }));
      continue;
    }
    paras.push(
      new Paragraph({
        text: stripped,
        spacing: { after: 80 },
      })
    );
  }

  // Unresolved items — keep per requirements
  if (options.includeUnresolvedMarkers && section.unresolvedItems.length > 0) {
    paras.push(
      new Paragraph({
        children: [new TextRun({ text: 'Unresolved items:', bold: true, color: 'C0392B' })],
        spacing: { before: 100, after: 60 },
      })
    );
    for (const item of section.unresolvedItems) {
      paras.push(
        new Paragraph({
          text: `• ${item}`,
          indent: { left: 360 },
          spacing: { after: 60 },
        })
      );
    }
  }

  return paras;
}

export async function exportToDocx(
  draft: ProposalDraft,
  pkg: ServicePackage | null,
  options: ExportOptions
): Promise<Blob> {
  const allParagraphs: Paragraph[] = [];

  // ── Title Page ──
  allParagraphs.push(
    new Paragraph({
      children: [
        new TextRun({
          text: options.includeDraftLabel ? `[DRAFT] ${draft.title}` : draft.title,
          bold: true,
          size: 48,
          color: '1B2A4A',
        }),
      ],
      heading: HeadingLevel.TITLE,
      alignment: AlignmentType.CENTER,
      spacing: { after: 200 },
    })
  );

  if (draft.clientName) {
    allParagraphs.push(
      new Paragraph({
        text: `Client: ${draft.clientName}`,
        alignment: AlignmentType.CENTER,
        spacing: { after: 100 },
      })
    );
  }

  if (pkg) {
    allParagraphs.push(
      new Paragraph({
        text: `Package: ${pkg.name}${pkg.isApproved ? ' (Approved)' : ''}`,
        alignment: AlignmentType.CENTER,
        spacing: { after: 100 },
      })
    );
  }

  allParagraphs.push(
    new Paragraph({
      text: `Generated: ${new Date().toLocaleDateString('en-GB', { day: '2-digit', month: 'long', year: 'numeric' })}`,
      alignment: AlignmentType.CENTER,
      spacing: { after: 400 },
    })
  );

  // Draft notice
  if (options.includeDraftLabel) {
    allParagraphs.push(
      new Paragraph({
        children: [
          new TextRun({
            text: 'DRAFT DOCUMENT — This proposal has been generated by the Proposal & Scope-of-Work Assistant. All commercial terms, pricing, and commitments require human review and authorisation before external use.',
            bold: true,
            italics: true,
            color: '8E6A00',
          }),
        ],
        spacing: { before: 200, after: 400 },
        border: {
          top: { style: BorderStyle.SINGLE, size: 6, color: 'F0C040' },
          bottom: { style: BorderStyle.SINGLE, size: 6, color: 'F0C040' },
        },
      })
    );
  }

  // Sections
  const sortedSections = [...draft.sections].sort((a, b) => a.order - b.order);
  for (const section of sortedSections) {
    allParagraphs.push(...sectionToDocxParagraphs(section, options));
  }

  // Confirmation questions
  if (options.includeConfirmationQuestions && draft.confirmationQuestions.length > 0) {
    allParagraphs.push(
      new Paragraph({
        text: 'Questions Requiring Client Confirmation',
        heading: HeadingLevel.HEADING_2,
        spacing: { before: 300, after: 100 },
      })
    );
    const unresolved = draft.confirmationQuestions.filter((q) => !q.isResolved);
    for (const q of unresolved) {
      allParagraphs.push(
        new Paragraph({
          text: `• ${q.question}`,
          indent: { left: 360 },
          spacing: { after: 80 },
        })
      );
    }
  }

  const doc = new Document({
    sections: [{ properties: {}, children: allParagraphs }],
    creator: 'Proposal & Scope-of-Work Assistant',
    description: 'Generated proposal draft — requires human review',
  });

  return await Packer.toBlob(doc);
}

// ─── PDF Export ──────────────────────────────────────────────────────────────

export function exportToPdf(draft: ProposalDraft, options: ExportOptions): Blob {
  const pdf = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' });

  const pageW = 210;
  const margin = 20;
  const contentW = pageW - margin * 2;
  const pageH = 297;
  const bottomMargin = 20;
  let y = margin;

  const navy = [27, 42, 74] as const;
  const teal = [0, 128, 128] as const;
  const amber = [142, 106, 0] as const;
  const red = [192, 57, 43] as const;

  function addPage() {
    pdf.addPage();
    y = margin;
  }

  function checkY(needed: number) {
    if (y + needed > pageH - bottomMargin) addPage();
  }

  function addText(text: string, fontSize: number, color: readonly [number, number, number], opts?: { bold?: boolean; italic?: boolean }) {
    pdf.setFontSize(fontSize);
    pdf.setTextColor(color[0], color[1], color[2]);
    if (opts?.bold) pdf.setFont('helvetica', opts.italic ? 'bolditalic' : 'bold');
    else if (opts?.italic) pdf.setFont('helvetica', 'italic');
    else pdf.setFont('helvetica', 'normal');

    const lines = pdf.splitTextToSize(text, contentW) as string[];
    const lineH = fontSize * 0.4;
    checkY(lines.length * lineH + 4);
    pdf.text(lines, margin, y);
    y += lines.length * lineH + 4;
  }

  // Title
  addText(options.includeDraftLabel ? `[DRAFT] ${draft.title}` : draft.title, 20, navy, { bold: true });
  if (draft.clientName) addText(`Client: ${draft.clientName}`, 11, [80, 80, 80]);
  addText(`Generated: ${new Date().toLocaleDateString('en-GB', { day: '2-digit', month: 'long', year: 'numeric' })}`, 10, [120, 120, 120]);
  y += 8;

  if (options.includeDraftLabel) {
    addText(
      'DRAFT — This document requires human review before external use. All commercial terms require authorisation.',
      9,
      amber,
      { bold: true, italic: true }
    );
    y += 6;
  }

  // Sections
  const sortedSections = [...draft.sections].sort((a, b) => a.order - b.order);
  for (const section of sortedSections) {
    checkY(20);
    addText(section.title, 13, teal, { bold: true });

    if (section.status !== 'confirmed') {
      const badge =
        section.status === 'missing'
          ? '[MISSING — INFORMATION NOT PROVIDED]'
          : '[SUGGESTED WORDING — REVIEW REQUIRED]';
      addText(badge, 9, section.status === 'missing' ? red : amber, { italic: true });
    }

    const cleaned = stripMarkdown(section.content);
    addText(cleaned, 10, [40, 40, 40]);

    if (options.includeUnresolvedMarkers && section.unresolvedItems.length > 0) {
      addText('Unresolved items:', 9, red, { bold: true });
      for (const item of section.unresolvedItems) {
        addText(`• ${item}`, 9, red);
      }
    }
    y += 4;
  }

  // Confirmation questions
  if (options.includeConfirmationQuestions && draft.confirmationQuestions.length > 0) {
    checkY(20);
    addText('Questions Requiring Client Confirmation', 13, teal, { bold: true });
    const unresolved = draft.confirmationQuestions.filter((q) => !q.isResolved);
    for (const q of unresolved) {
      addText(`• ${q.question}`, 10, [40, 40, 40]);
    }
  }

  // Footer on each page
  const totalPages = (pdf as unknown as { internal: { getNumberOfPages: () => number } }).internal.getNumberOfPages();
  for (let i = 1; i <= totalPages; i++) {
    pdf.setPage(i);
    pdf.setFontSize(8);
    pdf.setTextColor(150, 150, 150);
    pdf.text('Proposal & Scope-of-Work Assistant — Draft Document — Not authorised for external use', margin, pageH - 8);
    pdf.text(`Page ${i} of ${totalPages}`, pageW - margin - 20, pageH - 8);
  }

  return pdf.output('blob');
}

// ─── Plain Text Export ──────────────────────────────────────────────────────

export function exportToTxt(draft: ProposalDraft, options: ExportOptions): Blob {
  const lines: string[] = [];

  if (options.includeDraftLabel) {
    lines.push('='.repeat(70));
    lines.push('DRAFT DOCUMENT — REQUIRES HUMAN REVIEW BEFORE EXTERNAL USE');
    lines.push('='.repeat(70));
    lines.push('');
  }

  lines.push(draft.title);
  if (draft.clientName) lines.push(`Client: ${draft.clientName}`);
  lines.push(`Generated: ${new Date().toLocaleDateString()}`);
  lines.push('');

  const sortedSections = [...draft.sections].sort((a, b) => a.order - b.order);
  for (const section of sortedSections) {
    lines.push('─'.repeat(50));
    lines.push(section.title.toUpperCase());
    if (section.status !== 'confirmed') {
      lines.push(section.status === 'missing' ? '⚠ MISSING — INFORMATION NOT PROVIDED' : '⚠ SUGGESTED WORDING — REVIEW REQUIRED');
    }
    lines.push('');
    lines.push(stripMarkdown(section.content));
    if (options.includeUnresolvedMarkers && section.unresolvedItems.length > 0) {
      lines.push('');
      lines.push('Unresolved:');
      section.unresolvedItems.forEach((i) => lines.push(`  • ${i}`));
    }
    lines.push('');
  }

  if (options.includeConfirmationQuestions && draft.confirmationQuestions.length > 0) {
    lines.push('─'.repeat(50));
    lines.push('QUESTIONS REQUIRING CLIENT CONFIRMATION');
    lines.push('');
    draft.confirmationQuestions.filter((q) => !q.isResolved).forEach((q) => {
      lines.push(`• ${q.question}`);
    });
  }

  return new Blob([lines.join('\n')], { type: 'text/plain' });
}

// ─── Download Helper ─────────────────────────────────────────────────────────

export function downloadBlob(blob: Blob, filename: string): void {
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  a.click();
  URL.revokeObjectURL(url);
}

export function sanitizeFilename(title: string): string {
  return title
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 60);
}
